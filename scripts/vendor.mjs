/**
 * Bundles the code of the Quant-UX editor this server uses (see
 * editor-entry.js: QUX2HTML, TokenMapper, DesignSystem...) into
 * vendor/editor.js, so the agent gets the same HTML as the editor. The
 * bundle is committed: the server runs without a checkout of the app, and
 * this script runs again when that code changes in the app.
 *
 *   QUX_APP_SRC=../quant-ux/src npm run vendor
 *
 * The app code uses webpack aliases (common/, dojo/...) and imports without
 * extensions, which esbuild resolves with nodePaths, like jest does with
 * modulePaths.
 */
import { build } from 'esbuild'
import { execSync } from 'child_process'
import { fileURLToPath } from 'url'
import fs from 'fs'
import path from 'path'

const here = path.dirname(fileURLToPath(import.meta.url))
const appSrc = path.resolve(process.env.QUX_APP_SRC || path.join(here, '../../quant-ux/src'))

if (!fs.existsSync(path.join(appSrc, 'ai/QUX2HTML.js'))) {
  console.error(`vendor > no ai/QUX2HTML.js in ${appSrc}, set QUX_APP_SRC to the src/ folder of a quant-ux checkout`)
  process.exit(1)
}

await build({
  entryPoints: [path.join(here, 'editor-entry.js')],
  outfile: path.join(here, '../vendor/editor.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  nodePaths: [appSrc],
  logLevel: 'warning',
  banner: {
    js: `// Generated by scripts/vendor.mjs from the editor code of quant-ux ${revision(appSrc)}, do not edit`
  }
})
console.log(`vendor > built vendor/editor.js from ${appSrc}`)

function revision (dir) {
  try {
    const commit = execSync('git rev-parse --short HEAD', { cwd: dir }).toString().trim()
    const dirty = execSync('git status --porcelain -- ai core', { cwd: dir }).toString().trim()
    return `@${commit}${dirty ? ' (with local changes)' : ''}`
  } catch (e) {
    return ''
  }
}
