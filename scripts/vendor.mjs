/**
 * Bundles src/headless/DesignHandoff.js of the Quant-UX editor (and what it
 * imports: QUX2HTML, TokenMapper, DesignSystem...) into vendor/headless.js,
 * so the MCP server runs the same code as the editor. The bundle is
 * committed: the server runs without a checkout of the editor, and this
 * script runs again when the editor code changes.
 *
 *   QUX_APP_SRC=../quant-ux/src npm run vendor
 *
 * The app code uses webpack aliases (common/, dojo/...) and imports without
 * extensions, which esbuild resolves with nodePaths, like jest does with
 * modulePaths.
 */
import { build } from 'esbuild'
import { execSync } from 'child_process'
import { fileURLToPath } from 'url'
import fs from 'fs'
import path from 'path'

const here = path.dirname(fileURLToPath(import.meta.url))
const appSrc = path.resolve(process.env.QUX_APP_SRC || path.join(here, '../../quant-ux/src'))
const entry = path.join(appSrc, 'headless/DesignHandoff.js')

if (!fs.existsSync(entry)) {
  console.error(`vendor > no ${entry}, set QUX_APP_SRC to the src/ folder of a quant-ux checkout`)
  process.exit(1)
}

await build({
  entryPoints: [entry],
  outfile: path.join(here, '../vendor/headless.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  nodePaths: [appSrc],
  logLevel: 'warning',
  banner: {
    js: `// Generated by scripts/vendor.mjs from src/headless/DesignHandoff.js of quant-ux ${revision(appSrc)}, do not edit`
  }
})
console.log(`vendor > built vendor/headless.js from ${appSrc}`)

function revision (dir) {
  try {
    const commit = execSync('git rev-parse --short HEAD', { cwd: dir }).toString().trim()
    const dirty = execSync('git status --porcelain -- .', { cwd: dir }).toString().trim()
    return `@${commit}${dirty ? ' (with local changes)' : ''}`
  } catch (e) {
    return ''
  }
}
